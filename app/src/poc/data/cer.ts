export function getCER(categoria: string, tipologia: string): CerRecord | undefined {
  return CER_DATA.find(c => c.categoria === categoria && c.tipologia === tipologia)
}

export function getTierRobustezza(tier: string): 0 | 1 | 2 | 3 {
  const map: Record<string, 0 | 1 | 2 | 3> = {
    'L0-A': 0, 'L0-B': 0, 'L0-C': 0,
    'L1-A': 1, 'L1-B': 1, 'L1-B-DUAL': 1, 'L1-C': 1,
    'L2-B': 2, 'L2-B-DUAL': 2, 'L2-C': 2,
    'L2PLUS-A': 3, 'L2PLUS-B': 3
  }
  return map[tier] ?? 0
}
